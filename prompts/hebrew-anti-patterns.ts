/**
 * קבועים משותפים למניעת "עברית מתורגמת" בפרומפטים
 * Shared constants to prevent AI-typical Hebrew patterns across all prompts
 */

/**
 * ביטויים ש-Claude נוטה להשתמש בהם ושנשמעים כמו AI ולא כמו ישראלי
 */
export const HEBREW_AI_ANTI_PATTERNS = [
  'בהקשר זה',
  'חשוב לציין',
  'ראוי להדגיש',
  'ניתן לראות כי',
  'יש לציין כי',
  'מן הראוי',
  'כפי שצוין',
  'באופן משמעותי',
  'לאור האמור',
  'מכאן ניתן ללמוד',
  'יודגש כי',
  'אין ספק כי',
  'עם זאת יש לציין',
  'בהתייחס ל',
  'נדמה כי',
  'ניכר כי',
  'ברי כי',
  'יצוין כי',
  'ראוי לציין',
  'מעניין לציין',
];

/**
 * הוראה למניעת "מצב רשימות" — Claude נוטה לפתוח כל פסקה עם מילת קישור
 */
export const HEBREW_PARAGRAPH_FLOW_INSTRUCTION = `אל תפתח כל פסקה עם מילת קישור כמו "בנוסף", "יתרה מכך", "כמו כן", "זאת ועוד".
פסקה טובה בעברית מתחילה ישר בנושא — "הממשלה החליטה...", "מחירי הדירות עלו...", "הבעיה המרכזית היא...".
מותר להשתמש במילות קישור מדי פעם, אבל לא בכל פסקה.`;

/**
 * כללי כתיבה טבעית בעברית — 7 כללים קצרים וברורים
 */
export const HEBREW_NATURAL_WRITING_RULES = `כללי עברית טבעית:
1. משפט אחד = רעיון אחד. לא לדחוס 3 רעיונות למשפט ארוך
2. "כדי" ולא "על מנת" (אלא אם כן הסגנון משפטי/רשמי)
3. "לפי" ולא "בהתאם ל" (אלא אם כן רשמי)
4. "אפשר" ולא "ניתן" בשפה יומיומית. "ניתן" מתאים לשפה רשמית
5. לא לפתוח כל פסקה עם מילת קישור — להתחיל ישר בנושא
6. במקום "חשוב לציין ש..." / "ראוי להדגיש ש..." — פשוט לציין ולהדגיש
7. במקום "באופן משמעותי" — "מאוד" או "בצורה ניכרת"`;

/**
 * דוגמאות של ביטויים AI-אופייניים והחלופות הטבעיות שלהם
 */
export const HEBREW_BAD_GOOD_EXAMPLES = `ביטויים אסורים (AI-אופייניים) והחלופות שלהם:
❌ "חשוב לציין כי" → ✅ להשמיט — פשוט לציין
❌ "בהקשר זה" → ✅ להשמיט — להתחיל ישר ברעיון
❌ "ראוי להדגיש" → ✅ להשמיט — פשוט להדגיש
❌ "ניתן לראות כי" → ✅ "אפשר לראות ש" או להשמיט
❌ "לתת ערך" → ✅ "להועיל" / "לעזור"
❌ "בסוף היום" → ✅ "בסופו של דבר"
❌ "לקחת את זה לשלב הבא" → ✅ "להתקדם"
❌ "באופן משמעותי" → ✅ "מאוד" / "בצורה ניכרת"
❌ "מהווה" → ✅ "הוא" / "זה" (בשפה יומיומית)
❌ "על מנת" → ✅ "כדי"
❌ "בהתאם ל" → ✅ "לפי"
❌ "לאור האמור" → ✅ "לכן" / "בגלל זה"`;

/**
 * פונקציה שמייצרת בלוק הוראות anti-patterns מוכן לשתילה בפרומפט
 * @param includeExamples - האם לכלול דוגמאות bad/good (ברירת מחדל: true)
 * @returns טקסט מוכן לשתילה בפרומפט
 */
export function getAntiPatternInstruction(includeExamples: boolean = true): string {
  const antiPatternsList = HEBREW_AI_ANTI_PATTERNS.slice(0, 12).map(p => `"${p}"`).join(', ');

  let instruction = `
**⚠️ עברית טבעית — כללי ברזל:**

אל תשתמש בביטויים האלה (הם נשמעים כמו AI ולא כמו ישראלי):
${antiPatternsList}

${HEBREW_PARAGRAPH_FLOW_INSTRUCTION}

${HEBREW_NATURAL_WRITING_RULES}`;

  if (includeExamples) {
    instruction += `\n\n${HEBREW_BAD_GOOD_EXAMPLES}`;
  }

  return instruction;
}
